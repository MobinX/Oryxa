export const LANDING_STRINGS: Record<LandingLang, LandingStrings> = { en, bn };

/** Minimal browser surface, declared locally so this module compiles without the DOM lib. */
type BrowserGlobals = {
  localStorage?: { getItem(key: string): string | null };
  navigator?: { language?: string };
};

/** Stored choice wins; otherwise Bengali for bn locales or the Dhaka timezone. */
export function detectLandingLang(): LandingLang {
  try {
    const g = globalThis as unknown as BrowserGlobals;
    const stored = g.localStorage?.getItem('oo-lang');
    if (stored === 'bn' || stored === 'en') return stored;
    const nav = g.navigator?.language || '';
    if (nav.toLowerCase().startsWith('bn')) return 'bn';
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
    if (tz === 'Asia/Dhaka') return 'bn';
  } catch {
    /* private mode — fall through to English */
  }
  return 'en';
}
